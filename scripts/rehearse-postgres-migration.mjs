import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { DatabaseSync } from 'node:sqlite';
import pg from 'pg';

const { Client } = pg;
const [snapshot, reportPath, ...flags] = process.argv.slice(2);
const verifyOnly = flags.includes('--verify-only');
const withRuntime = flags.includes('--with-runtime');
const isolated = new Set(['espressoulster_runtime_staging','espressoulster_pg_fixture','espressoulster_load_staging']);
const destination = process.env.PGDATABASE || 'espressoulster_rehearsal';
if (!snapshot || !reportPath || flags.some(flag=>!['--verify-only','--with-runtime'].includes(flag))) {
  console.error('Usage: PGHOST=/private/socket PGPORT=55432 node scripts/rehearse-postgres-migration.mjs snapshot.sqlite report.json [--verify-only] [--with-runtime]');
  process.exit(2);
}
if (!process.env.PGHOST?.startsWith('/') || (withRuntime ? !isolated.has(destination) : destination !== 'espressoulster_rehearsal')) {
  console.error('This rehearsal requires a private PostgreSQL Unix socket and the dedicated rehearsal database.');
  process.exit(2);
}
const rowidTables = new Set(['booking_notifications','order_events','orders','payments','settings','subscription_catalog','subscription_item_codes']);

class CheckError extends Error {}
const check = (condition, description) => { if (!condition) throw new CheckError(description); };
const sqlName = value => '"' + value.replaceAll('"', '""') + '"';
const checksum = value => createHash('sha256').update(value).digest('hex');
const selectedColumns = columns => columns.map(column => sqlName(column.name)).join(', ');

function sqliteRows(db, table, columns) {
  const statement = db.prepare(`SELECT ${selectedColumns(columns)} FROM ${sqlName(table)}`);
  statement.setReadBigInts(true);
  statement.setReturnArrays(true);
  return statement.iterate();
}

function schemaSql(object) {
  // The SQLite catalog provides the table definitions, constraints and indexes.
  // Rewrite the constructs present in this app, leaving PostgreSQL to validate
  // the result. Triggers and views are tracked separately for a manual port.
  const asSql = object.sql.replace(/`([^`]+)`/g, (_, name) => sqlName(name));
  const translated = asSql.split(/('(?:[^']|'')*')/).map((part, index) => {
    if (index % 2) return part;
    return part
      .replace(/\binteger\s+PRIMARY KEY\s+AUTOINCREMENT\b/gi, 'bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
      .replace(/\binteger\b/gi, 'bigint')
      .replace(/\btimestamp\b/gi, 'text')
      .replace(/\bblob\b/gi, 'bytea')
      .replace(/\bDEFAULT\s+CURRENT_TIMESTAMP\b/gi, "DEFAULT (to_char(statement_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))")
      .replace(/\bunixepoch\(\)/gi, 'floor(extract(epoch FROM statement_timestamp()))::bigint')
      .replace(/\blower\(hex\(randomblob\(16\)\)\)/gi, "replace(gen_random_uuid()::text, '-', '')");
  }).join('');

  // Cloudflare's imported metadata has BLOB affinity, but this particular
  // field stores an integer. Retain its storage class through the transfer.
  return object.name === '_cf_METADATA'
    ? translated.replace(/\bvalue\s+bytea\b/i, 'value bigint').replace(/_cf_METADATA/g, sqlName(object.name))
    : translated;
}

function dataType(table, column) {
  if (table === '_cf_METADATA' && column.name === 'value') return 'integer';
  switch (column.type.toUpperCase()) {
    case 'INTEGER': return 'integer';
    case 'TIMESTAMP':
    case 'TEXT': return 'text';
    case 'BLOB': return 'bytes';
    default: throw new CheckError(`Unmapped column type in ${table}.${column.name}`);
  }
}

function normalize(value, type, fromPostgres) {
  if (value === null) return null;
  if (type === 'integer') {
    const expected = fromPostgres ? typeof value === 'string' && /^-?\d+$/.test(value) : typeof value === 'bigint';
    check(expected, 'An integer field contains a different storage type.');
    return BigInt(value).toString();
  }
  if (type === 'bytes') {
    check(value instanceof Uint8Array, 'A binary field contains a different storage type.');
    return Buffer.from(value).toString('hex');
  }
  check(typeof value === 'string' && !value.includes('\0'), 'A text field contains a different storage type or an unsupported NUL.');
  return value;
}

function fingerprint(rows, types, fromPostgres = false) {
  const rowHashes = new Map();
  let count = 0;
  for (const row of rows) {
    const hash = checksum(JSON.stringify(row.map((cell, index) => normalize(cell, types[index], fromPostgres))));
    rowHashes.set(hash, (rowHashes.get(hash) ?? 0) + 1);
    count++;
  }
  // Ignore database ordering while preserving identical-row multiplicity.
  const wholeTable = createHash('sha256');
  for (const hash of [...rowHashes.keys()].sort()) wholeTable.update(`${hash}:${rowHashes.get(hash)}\n`);
  return { count, digest: wholeTable.digest('hex') };
}

function orderedTables(source, tables) {
  const remaining = new Map(tables.map(table => [table.name, table]));
  const sorted = [];
  while (remaining.size) {
    const processed = sorted.length;
    for (const table of remaining.values()) {
      const parents = source.prepare('SELECT "table" AS parent FROM pragma_foreign_key_list(?)').all(table.name);
      if (parents.some(({ parent }) => parent !== table.name && remaining.has(parent))) continue;
      sorted.push(table);
      remaining.delete(table.name);
    }
    check(sorted.length > processed, 'Circular foreign keys need a separate migration.');
  }
  return sorted;
}

async function copyRows(client, table, columns, source) {
  const types = columns.map(column => dataType(table, column));
  const chunkSize = Math.min(200, Math.floor(32000 / columns.length));
  let rows = [];
  const flush = async () => {
    const params = rows.flatMap(row => row.map(value => value instanceof Uint8Array ? Buffer.from(value) : value));
    const groups = rows.map((row, i) => '(' + row.map((_, j) => '$' + (i * columns.length + j + 1)).join(', ') + ')');
    await client.query(`INSERT INTO ${sqlName(table)} (${selectedColumns(columns)}) VALUES ${groups.join(', ')}`, params);
    rows = [];
  };
  for (const row of sqliteRows(source, table, columns)) {
    row.forEach((cell, index) => normalize(cell, types[index], false));
    rows.push(row);
    if (rows.length === chunkSize) await flush();
  }
  if (rows.length) await flush();
}

let phase = 'opening the backup';
const client = new Client({ database: destination, connectionTimeoutMillis: 5000 });
let source;
try {
  source = new DatabaseSync(snapshot, {readOnly:true});
  check(source.prepare('PRAGMA integrity_check').get().integrity_check === 'ok', 'Invalid SQLite snapshot.');
  check(!source.prepare('PRAGMA foreign_key_check').get(), 'SQLite snapshot contains broken foreign keys.');
  const catalog = source.prepare("SELECT type,name,sql FROM sqlite_schema WHERE name NOT LIKE 'sqlite_%' AND sql IS NOT NULL ORDER BY name").all();
  const tables = orderedTables(source, catalog.filter(object => object.type === 'table'));
  const indexes = catalog.filter(object => object.type === 'index');
  const identities = source.prepare('SELECT name,CAST(seq AS TEXT) AS seq FROM sqlite_sequence ORDER BY name').all();
  check(tables.length > 0, 'The snapshot contains no tables.');
  phase = 'opening the isolated PostgreSQL database';
  await client.connect();
  const instance = (await client.query('SELECT current_database() AS db, inet_server_addr() AS network')).rows[0];
  check(instance.db === destination && instance.network === null, 'Refusing a database outside the private rehearsal socket.');
  await client.query('BEGIN');
  await client.query("SET LOCAL statement_timeout='30s'; SET LOCAL lock_timeout='3s'; SET LOCAL search_path=public,pg_catalog");
  const existing = (await client.query("SELECT tablename FROM pg_tables WHERE schemaname='public'")).rows.map(row => row.tablename).sort();
  if (!verifyOnly) {
    check(existing.length === 0, 'Refusing to import into a database containing tables.');
    for (const table of tables) {
      phase = `creating ${table.name}`;
      await client.query(schemaSql(table));
      if (withRuntime && rowidTables.has(table.name)) {
        await client.query(`ALTER TABLE ${sqlName(table.name)} ADD COLUMN rowid bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE`);
      }
    }
  } else {
    check(JSON.stringify(existing) === JSON.stringify(tables.map(table => table.name).sort()), 'Destination tables differ from the SQLite snapshot.');
  }
  const runtimeObjects = catalog.filter(object=>object.type === 'trigger' || object.type === 'view')
    .map(({type,name})=>({type,name})).sort((a,b)=>a.type.localeCompare(b.type) || a.name.localeCompare(b.name));
  const report = { verifiedAt:new Date().toISOString(), dataOnly:!withRuntime, tables:[], rows:0, indexes:indexes.length, sequences:[],
    pendingRuntimeObjects:withRuntime ? [] : runtimeObjects };
  for (const table of tables) {
    phase = `copying and checking ${table.name}`;
    const columns = source.prepare('SELECT name,type,hidden FROM pragma_table_xinfo(?) ORDER BY cid').all(table.name);
    check(columns.length && columns.every(column => column.hidden === 0), 'Generated or hidden columns need a separate migration.');
    if (withRuntime && rowidTables.has(table.name)) columns.push({name:'rowid',type:'INTEGER'});
    if (!verifyOnly) await copyRows(client, table.name, columns, source);
    const types = columns.map(column => dataType(table.name, column));
    const expected = fingerprint(sqliteRows(source, table.name, columns), types);
    const result = await client.query({ text:`SELECT ${selectedColumns(columns)} FROM ${sqlName(table.name)}`, rowMode:'array' });
    const actual = fingerprint(result.rows, types, true);
    check(expected.count === actual.count && expected.digest === actual.digest, `Row verification failed for ${table.name}.`);
    report.tables.push({ name:table.name, rows:expected.count, verified:true });
    report.rows += expected.count;
  }
  for (const index of indexes) if (!verifyOnly) {
    phase = `creating index ${index.name}`;
    await client.query(schemaSql(index));
  }
  phase = 'checking indexes';
  const indexNames = new Set((await client.query("SELECT indexname FROM pg_indexes WHERE schemaname='public'")).rows.map(row=>row.indexname));
  check(indexes.every(index=>indexNames.has(index.name)), 'One or more copied indexes are missing.');
  for (const {name,seq} of identities) {
    phase = `checking the identity counter for ${name}`;
    const column = source.prepare('SELECT name FROM pragma_table_info(?) WHERE pk=1').get(name).name;
    const sequence = (await client.query('SELECT pg_get_serial_sequence($1,$2) AS name', [sqlName(name),column])).rows[0].name;
    check(sequence, `Missing generated identity for ${name}.`);
    if (!verifyOnly) await client.query('SELECT setval($1::regclass,$2::bigint,true)', [sequence,seq]);
    const targetValue = (await client.query(`SELECT last_value::text AS value FROM ${sequence}`)).rows[0].value;
    check(targetValue === seq, `Identity counter does not match for ${name}.`);
    report.sequences.push({ table:name, verified:true });
  }
  if (withRuntime) {
    for (const name of rowidTables) {
      phase = `checking row order for ${name}`;
      const seq = source.prepare(`SELECT CAST(MAX(rowid) AS TEXT) AS max FROM ${sqlName(name)}`).get().max;
      if (seq !== null && BigInt(seq) > 0n) {
        const sequence = (await client.query("SELECT pg_get_serial_sequence($1,'rowid') AS name", [sqlName(name)])).rows[0].name;
        check(sequence, `Missing row order counter for ${name}.`);
        if (!verifyOnly) await client.query('SELECT setval($1::regclass,$2::bigint,true)', [sequence,seq]);
        const target = (await client.query(`SELECT last_value::text AS value FROM ${sequence}`)).rows[0].value;
        check(target === seq, `Row order counter does not match for ${name}.`);
      }
    }
    phase = 'installing and checking PostgreSQL triggers and views';
    if (!verifyOnly) {
      for (const name of ['functions.sql','runtime-rules.sql']) {
        await client.query(await readFile(new URL('../server/postgres/'+name,import.meta.url),'utf8'));
      }
    }
    const imported = (await client.query(`SELECT DISTINCT 'trigger' AS type,trigger_name AS name
      FROM information_schema.triggers WHERE trigger_schema='public'
      UNION ALL SELECT 'view',table_name FROM information_schema.views WHERE table_schema='public' ORDER BY type,name`)).rows;
    check(JSON.stringify(imported) === JSON.stringify(runtimeObjects), 'PostgreSQL trigger/view names differ from the source.');
    report.installedRuntimeObjects = imported;
  }
  await client.query(verifyOnly ? 'ROLLBACK' : 'COMMIT');
  await writeFile(reportPath, JSON.stringify(report, null, 2) + '\n', {mode:0o600,flag:'wx'});
  console.log(`Verified ${report.rows} rows across ${report.tables.length} tables.`, withRuntime
    ? `Verified ${runtimeObjects.length} PostgreSQL trigger/view definitions.`
    : `${report.pendingRuntimeObjects.length} SQLite triggers/views need a separate runtime port.`);
} catch (error) {
  await client.query('ROLLBACK').catch(() => {});
  const reason = error instanceof CheckError ? error.message : `database error ${error.code ?? 'unknown'}`;
  console.error(`Rehearsal stopped while ${phase}: ${reason}`);
  process.exitCode = 1;
} finally {
  source?.close();
  await client.end().catch(() => {});
}
